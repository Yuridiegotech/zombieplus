document.addEventListener('DOMContentLoaded', () => {
  // ──────────────────────────────────────────
  //  Modal functionality for Roadmap image
  // ──────────────────────────────────────────
  const modal = document.getElementById('roadmapModal');
  const roadmapCard = document.querySelector('.roadmap-card');
  const modalClose = document.querySelector('.modal-close');

  if (roadmapCard && modal) {
    roadmapCard.addEventListener('click', () => {
      modal.classList.add('active');
      document.body.style.overflow = 'hidden';
    });

    modalClose.addEventListener('click', () => {
      modal.classList.remove('active');
      document.body.style.overflow = 'auto';
    });

    modal.addEventListener('click', (e) => {
      if (e.target === modal) {
        modal.classList.remove('active');
        document.body.style.overflow = 'auto';
      }
    });
  }

  // ──────────────────────────────────────────
  //  Load Allure Real Metrics & History
  //  Sources (tried in order):
  //    1. runs-manifest.json   (generated by CI)
  //    2. history-trend.json   (root or in latest/)
  // ──────────────────────────────────────────

  const MANIFEST_URL = './allure-report/runs-manifest.json';
  const TREND_URLS   = [
    './allure-report/latest/widgets/history-trend.json',
    './allure-report/history-trend.json'
  ];

  // Helpers ──────────────────────────────────
  function cacheBust(url) {
    return url + '?t=' + Date.now();
  }

  async function fetchJSON(url) {
    try {
      const r = await fetch(cacheBust(url));
      if (!r.ok) return null;
      return await r.json();
    } catch { return null; }
  }

  function formatDate(iso) {
    if (!iso) return '';
    try {
      const d = new Date(iso);
      return d.toLocaleDateString('pt-BR', { day: '2-digit', month: 'short', year: 'numeric' })
           + ' ' + d.toLocaleTimeString('pt-BR', { hour: '2-digit', minute: '2-digit' });
    } catch { return iso; }
  }

  // ──────────────────────────────────────────
  //  Render logic
  // ──────────────────────────────────────────
  function updateLiveCard(passed, total, failed) {
    const rate = total > 0 ? Math.round((passed / total) * 100) : 0;

    const passEl = document.querySelector('.report-stat-item .val.pass');
    if (passEl) passEl.textContent = `${passed} / ${total}`;

    const rateEl = document.querySelector('.report-stat-item .val.rate');
    if (rateEl) {
      rateEl.textContent = `${rate}%`;
      rateEl.style.color = rate === 100 ? 'var(--primary)' : (rate >= 90 ? '#facc15' : 'var(--accent-red)');
    }
  }

  function renderHistoryList(runs) {
    const listEl = document.getElementById('historyRunsList');
    if (!listEl) return;
    listEl.innerHTML = '';

    runs.forEach((run, idx) => {
      const isLatest = idx === 0;
      const a = document.createElement('a');
      a.href = run.url;
      a.target = '_blank';
      a.className = 'run-item' + (isLatest ? ' latest' : '');

      const statusIcon = run.failed === 0 ? 'fa-circle-check' : 'fa-circle-xmark';
      const statusColor = run.failed === 0 ? 'var(--primary)' : 'var(--accent-red)';
      const statusText  = run.failed === 0
        ? `${run.passed}/${run.total} Passou`
        : `${run.passed}/${run.total} (${run.failed} falha${run.failed > 1 ? 's' : ''})`;

      a.innerHTML = `
        <div class="run-info">
          <span class="run-badge">#${run.buildNum}</span>
          <div>
            <div style="font-weight: 600; font-size: 14px;">
              ${isLatest ? 'Regressão Docker-Compose (Última)' : 'Execução Regressão CI'}
            </div>
            <div class="run-date">${run.date || (isLatest ? 'Execução Mais Recente' : `Build #${run.buildNum}`)}</div>
          </div>
        </div>
        <div class="run-status">
          <i class="fa-solid ${statusIcon}" style="color: ${statusColor}"></i>
          ${statusText}
        </div>
      `;
      listEl.appendChild(a);
    });
  }

  // ──────────────────────────────────────────
  //  Data loading
  // ──────────────────────────────────────────
  async function loadFromManifest() {
    const manifest = await fetchJSON(MANIFEST_URL);
    if (!manifest || !Array.isArray(manifest.runs) || manifest.runs.length === 0) return false;

    const runsToShow = manifest.runs.slice(0, 5);
    const latest = runsToShow[0];

    // Update live card
    updateLiveCard(latest.passed ?? 0, latest.total ?? 0, latest.failed ?? 0);

    // Build run entries
    const entries = runsToShow.map((run, idx) => ({
      buildNum: run.buildNum || run.runNumber || '?',
      url: idx === 0 ? './allure-report/latest/' : `./allure-report/${run.buildNum || run.runNumber}/`,
      passed: run.passed ?? 0,
      total: run.total ?? 0,
      failed: run.failed ?? 0,
      date: formatDate(run.date)
    }));

    renderHistoryList(entries);
    return true;
  }

  async function loadFromHistoryTrend() {
    let data = null;
    for (const url of TREND_URLS) {
      data = await fetchJSON(url);
      if (Array.isArray(data) && data.length > 0) break;
      data = null;
    }
    if (!data) return false;

    const runsToShow = data.slice(0, 5);
    const latest = runsToShow[0];

    const latestBuild = latest.buildOrder ?? latest.data?.buildOrder ?? 0;
    const passed = latest.data?.passed ?? 0;
    const total  = latest.data?.total  ?? 0;
    const failed = (latest.data?.failed || 0) + (latest.data?.broken || 0);

    updateLiveCard(passed, total, failed);

    const entries = runsToShow.map((run, idx) => {
      const bNum = run.buildOrder ?? run.data?.buildOrder ?? (latestBuild - idx);
      const rPassed = run.data?.passed ?? 0;
      const rTotal  = run.data?.total  ?? 0;
      const rFailed = (run.data?.failed || 0) + (run.data?.broken || 0);
      return {
        buildNum: bNum,
        url: idx === 0 ? './allure-report/latest/' : `./allure-report/${bNum}/`,
        passed: rPassed,
        total: rTotal,
        failed: rFailed,
        date: ''
      };
    });

    renderHistoryList(entries);
    return true;
  }

  async function loadAllureData() {
    // Try manifest first (CI-generated), then history-trend (Allure native)
    const ok = await loadFromManifest() || await loadFromHistoryTrend();

    if (!ok) {
      // If neither source is available keep the static fallback HTML
      const listEl = document.getElementById('historyRunsList');
      if (listEl && listEl.querySelector('.loading-placeholder')) {
        listEl.innerHTML = `
          <div class="run-item" style="justify-content: center; color: var(--text-dim);">
            <i class="fa-solid fa-info-circle" style="margin-right: 8px;"></i>
            Os dados de histórico estarão disponíveis após a primeira execução do CI.
          </div>
        `;
      }
    }
  }

  loadAllureData();

  // ──────────────────────────────────────────
  //  Animated metric counters
  // ──────────────────────────────────────────
  const counters = document.querySelectorAll('.metric-num');
  counters.forEach(counter => {
    const target = parseInt(counter.getAttribute('data-target') || counter.innerText.replace(/\D/g, ''), 10);
    if (!isNaN(target)) {
      let current = 0;
      const increment = Math.ceil(target / 40);
      const suffix = counter.innerText.includes('%') ? '%' : (counter.innerText.includes('+') ? '+' : '');
      const timer = setInterval(() => {
        current += increment;
        if (current >= target) {
          counter.innerText = target + suffix;
          clearInterval(timer);
        } else {
          counter.innerText = current + suffix;
        }
      }, 30);
    }
  });

  // ──────────────────────────────────────────
  //  Smooth scroll for anchor links
  // ──────────────────────────────────────────
  document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', (e) => {
      const target = document.querySelector(anchor.getAttribute('href'));
      if (target) {
        e.preventDefault();
        target.scrollIntoView({ behavior: 'smooth', block: 'start' });
      }
    });
  });
});
